import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { stripeSignatureValid, billingKeyAllowed } from "../lib/billing-policy";
import { mutationAllowed, safeInternalPath } from "../lib/request-policy";
const now = new Date("2026-11-03T20:00:00Z").getTime();
const timestamp = String(now / 1000);
const payload = '{"type":"checkout.session.completed"}';
const signature = createHmac("sha256", "fixture-secret").update(`${timestamp}.${payload}`).digest("hex");
assert.equal(stripeSignatureValid(payload, `t=${timestamp},v1=${signature}`, "fixture-secret", now), true);
assert.equal(stripeSignatureValid(payload + " ", `t=${timestamp},v1=${signature}`, "fixture-secret", now), false);
assert.equal(stripeSignatureValid(payload, `t=${timestamp},v1=${signature}`, "fixture-secret", now + 301000), false);
assert.equal(stripeSignatureValid(payload, `t=${timestamp},v1=not-hex`, "fixture-secret", now), false);
assert.equal(stripeSignatureValid(payload, null, "fixture-secret", now), false);
assert.equal(billingKeyAllowed("sk_live_fixture", "preview", true), false);
assert.equal(billingKeyAllowed("sk_live_fixture", "production", false), false);
assert.equal(billingKeyAllowed("sk_live_fixture", "production", true), true);
assert.equal(billingKeyAllowed("sk_test_fixture", "preview", false), true);
assert.equal(billingKeyAllowed(undefined, "production", true), false);
for (const path of ["https://evil.test", "//evil.test", "/\\evil.test", "/\n/evil.test", null]) assert.equal(safeInternalPath(path), "/dashboard");
assert.equal(safeInternalPath("/dashboard/courses?next=1"), "/dashboard/courses?next=1");
assert.equal(mutationAllowed("https://academy.test/api/profile", "https://evil.test", null), false);
assert.equal(mutationAllowed("https://academy.test/api/profile", null, "cross-site"), false);
assert.equal(mutationAllowed("https://academy.test/api/profile", "https://academy.test", "same-origin"), true);
console.log("Request, redirect and billing security assertions passed.");
